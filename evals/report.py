"""Turn one or more result runs into a Markdown comparison. Spends nothing.

    python evals/report.py run-a run-b --confirm A:B --out docs/report.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent
sys.path[:0] = [str(ROOT), str(ROOT.parent / "services" / "api")]

from metrics import combine_confirmation, score_all  # noqa: E402


def fmt(value: float | None, kind: str = "pct") -> str:
    if value is None:
        return "n/a"
    if kind == "pct":
        return f"{value * 100:.0f}%"
    if kind == "usd":
        return f"${value:.4f}"
    if kind == "ms":
        return f"{value / 1000:.1f}s"
    return f"{value:.0f}"


def load(run_ids: list[str]) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for run_id in run_ids:
        public = ROOT / "results" / run_id / "results.jsonl"
        path = public if public.exists() else ROOT / "dataset" / "private" / "results" / run_id / "results.jsonl"
        with path.open() as handle:
            records.extend(json.loads(line) for line in handle if line.strip())
    return records


def build(records: list[dict[str, Any]], confirmations: list[tuple[str, str]], title: str) -> str:
    by_config: dict[str, list[dict[str, Any]]] = {}
    for record in records:
        by_config.setdefault(record["config"], []).append(record)
    labels = {name: f"{r[0]['model']} / {r[0]['effort']}{' + page' if r[0]['page_context'] else ''}" for name, r in by_config.items()}

    derived: dict[str, list[dict[str, Any]]] = {}
    for fast, confirm in confirmations:
        if fast in by_config and confirm in by_config:
            name = f"{fast}→{confirm}"
            derived[name] = combine_confirmation(by_config[fast], by_config[confirm])
            labels[name] = f"{labels[fast]}, then confirm with {labels[confirm]} (derived)"

    scores = {name: score_all(items) for name, items in {**by_config, **derived}.items()}
    provenance = sorted({r["provenance"] for r in records})
    out = [
        f"# {title}",
        "",
        f"Data: {', '.join(provenance)}. Generated by `evals/report.py` from recorded runs.",
        "",
        "| Config | Model | Cases | Precision | Recall | False alerts | Localised | Abstain kept | Line reads | p50 | p95 | $/analysis |",
        "|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|",
    ]
    for name, score in scores.items():
        out.append(
            f"| {name} | {labels[name]} | {score['records']} | {fmt(score['alert_precision'])} | {fmt(score['alert_recall'])} | "
            f"{score['false_alerts']} | {fmt(score['first_error_localisation'])} | {fmt(score['abstain_respected'])} | "
            f"{fmt(score['transcription']['line_accuracy'])} | {fmt(score['latency_p50_ms'], 'ms')} | {fmt(score['latency_p95_ms'], 'ms')} | "
            f"{fmt(score['cost_per_analysis_usd'], 'usd')} |"
        )
    out += ["", "## Reading and cost detail", "", "| Config | Case reads | Char errors | Superscript misses | Operation labels | Output tokens | Reasoning tokens | Cached input | Failed | Spend |", "|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
    for name, score in scores.items():
        t = score["transcription"]
        out.append(
            f"| {name} | {fmt(t['case_accuracy'])} | {fmt(t['character_error_rate'])} | {t['superscript_misses']}/{t['superscripts']} | "
            f"{fmt(score['operation_accuracy'])} | {fmt(score['output_tokens_mean'], 'n')} | {fmt(score['reasoning_tokens_mean'], 'n')} | "
            f"{fmt(score['cached_input_share'])} | {score['failed_requests']} | {fmt(score['total_cost_usd'], 'usd')} |"
        )
    out += ["", "## Every wrong outcome", ""]
    any_wrong = False
    for name, score in scores.items():
        for item in score["wrong"]:
            any_wrong = True
            out.append(f"- **{name} · {item['kind']} · {item['case']}**: wanted `{item['expected']}`, got `{item['predicted']}` (reason: {item['reason']}). Truth `{item['truth']}`, read `{item['read']}`.")
    if not any_wrong:
        out.append("None.")
    out += ["", "## Misread lines", ""]
    any_misread = False
    for name, score in scores.items():
        for item in score["transcription"]["failures"]:
            any_misread = True
            out.append(f"- {name} · {item['case']}: `{item['truth']}` read as `{item['read']}`")
    if not any_misread:
        out.append("None.")
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("runs", nargs="+")
    parser.add_argument("--confirm", action="append", default=[], help="FAST:CONFIRM, derive the two-reading result")
    parser.add_argument("--title", default="Model comparison")
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()
    pairs = [tuple(item.split(":")) for item in args.confirm]
    records = load(args.runs)
    text = build(records, pairs, args.title)  # type: ignore[arg-type]
    if args.out:
        private = ROOT / "dataset" / "private"
        if any(r["provenance"] == "real" for r in records) and private not in args.out.resolve().parents:
            # The report quotes misread lines, which are the contributor's writing.
            parser.error(f"this report contains real handwriting data, so --out must be inside {private}")
        args.out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
